// Request authentication & tenant isolation.
//
// Every authenticated request resolves its organization from the session row,
// never from client-supplied input.

pub mod auth;
pub mod rbac;

pub const SESSION_COOKIE: &str = "eat_session";

/// Best-effort client IP; trusts the first X-Forwarded-For hop set by the proxy.
pub fn client_ip(headers: &axum::http::HeaderMap) -> Option<String> {
    headers
        .get("x-forwarded-for")
        .and_then(|v| v.to_str().ok())
        .and_then(|v| v.split(',').next())
        .map(|v| v.trim().to_string())
        .filter(|v| !v.is_empty())
        .or_else(|| {
            headers
                .get("x-real-ip")
                .and_then(|v| v.to_str().ok())
                .map(|v| v.to_string())
        })
}

pub fn user_agent(headers: &axum::http::HeaderMap) -> Option<String> {
    headers
        .get(axum::http::header::USER_AGENT)
        .and_then(|v| v.to_str().ok())
        .map(|v| v.to_string())
}
